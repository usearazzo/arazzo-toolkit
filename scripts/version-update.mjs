// Writes the version of the package in the working directory to its
// src/version.ts and stages it: run as the package's `version` lifecycle
// script, which `lerna version` runs after bumping package.json and before
// committing, so the file lands in the release commit.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const { version } = JSON.parse(readFileSync('package.json', 'utf8'));
const file = 'src/version.ts';

writeFileSync(
  file,
  `// generated by scripts/version-update.mjs from package.json; do not edit
const version = '${version}';

export default version;
`,
);
execFileSync('git', ['add', file]);
